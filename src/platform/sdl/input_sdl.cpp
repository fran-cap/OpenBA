// True when the game window has SDL's keyboard focus (the window is the foreground
// window, as DISCL_FOREGROUND / GetForegroundWindow require).
bool GameWindowHasKeyboardFocus() {
    return SDL_GetKeyboardFocus() == Window::Sdl::GameWindow();
}

// SDL's key state with the platform's key layer applied (platform_input_hooks.h: the Mac
// layer on Apple, identity elsewhere). `scratch` receives the result when the layer changes it.
const bool* EffectiveKeyState(int* count, bool (&scratch)[kKeyLayerCapacity]) {
    const bool* raw = SDL_GetKeyboardState(count);
    return ApplyKeyLayer(raw, count, scratch);
}

// ReadMouse's sub-pixel remainder: SDL's relative motion is float, DirectInput's mickeys
// are integers. The remainder is carried so slow motion is not truncated away.
float g_remainderX = 0.0f;
float g_remainderY = 0.0f;

// The wheel since the last pump: the sum of the queued wheel events' vertical motion
// (flipped devices negated). PEEKED, not removed: the frame's pump still dispatches each
// one as WM_MOUSEWHEEL (the legacy path's OnMouseWheelMessage), and drains the queue every
// tick, so each event is counted by exactly one poll.
float WheelSinceLastPump() {
    SDL_Event events[64];
    const int n = SDL_PeepEvents(events, 64, SDL_PEEKEVENT, SDL_EVENT_MOUSE_WHEEL,
                                 SDL_EVENT_MOUSE_WHEEL);
    float sum = 0.0f;
    for (int i = 0; i < n; ++i) {
        const SDL_MouseWheelEvent& w = events[i].wheel;
        sum += (w.direction == SDL_MOUSEWHEEL_FLIPPED) ? -w.y : w.y;
    }
    return sum;
}

// Plan §G3 option (b), chosen from the I3 measurement (the I3 commit): SDL's relative
// mode while the middle button is held. In it SDL reads raw input (unscaled:
// SDL_HINT_MOUSE_RELATIVE_SYSTEM_SCALE stays at its default, off), so x / y are mickeys as
// DirectInput's were, and they keep coming with the cursor against the screen edge. SDL
// also hides the cursor and confines it to the window for the drag, and on release puts it
// back where SDL's own pointer moved to: retail's cursor stayed visible and free during a
// rotate. Outside the drag x / y stay the cursor-position difference.
// P8: where the system shows the pointer where the drag began once relative mode ends
// (RotateDragReturnsCursor: Android's pointer capture), SDL's position is put back there too,
// and the warp's own motion is drained, so neither the cursor nor the next poll's x / y jump.
bool g_rotateDrag = false;
float g_dragStartX = 0.0f;
float g_dragStartY = 0.0f;

void SetRotateDrag(bool on) {
    if (on == g_rotateDrag) return;
    SDL_Window* w = Window::Sdl::GameWindow();
    if (w == nullptr) return;
    if (on) SDL_GetMouseState(&g_dragStartX, &g_dragStartY);
    if (!SDL_SetWindowRelativeMouseMode(w, on)) return;
    g_rotateDrag = on;
    if (!on && RotateDragReturnsCursor()) {
        SDL_WarpMouseInWindow(w, g_dragStartX, g_dragStartY);
        SDL_GetRelativeMouseState(nullptr, nullptr);
    }
}

// The live, LOGICAL buttons (SDL_GetGlobalMouseState: GetAsyncKeyState with
// SM_SWAPBUTTON applied, SDL_windowsmouse.c), as DirectInput's rgbButtons order.
SDL_MouseButtonFlags LiveButtons() {
    const SDL_MouseButtonFlags b = SDL_GetGlobalMouseState(nullptr, nullptr);
    return PolledMouseButtons(b);
}

