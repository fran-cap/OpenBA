void SetTextEntryActive(bool active) {
    static bool s_active = false;
    if (active == s_active) return;
    s_active = active;
    TextEntryChanged(active);
}

int32_t ReadKeyboard(void* /*device*/, uint8_t dik[256]) {
    if (!GameWindowHasKeyboardFocus()) return kNotAcquired;
#if BANISHED_TWEAK_OVERLAY
    if (Diag::TweakOverlay::IsOpen()) {   // the debug tweak overlay has the keyboard: every key released
        std::memset(dik, 0, 256);
        return kOk;
    }
#endif

    int count = 0;
    bool scratch[kKeyLayerCapacity];
    const bool* state = EffectiveKeyState(&count, scratch);
    if (count > kSdlScancodeCount) count = kSdlScancodeCount;

    std::memset(dik, 0, 256);
    for (int s = 0; s < count; ++s) {
        if (state[s]) dik[kSdlScancodeToDik[s]] = kDiKeyDown;
    }
    AddScreenKeys(dik);
    return kOk;
}

bool IsForeground(void* /*window*/) {
    // `window` is the game window's native handle, the only window there is.
    return GameWindowHasKeyboardFocus();
}

// ---------------------------------------------------------------------------
// The mouse (SDL step I3).
//
// RETAIL PlatformGetMouseState 0x1800e1e10: DirectInput mouse (DISCL_FOREGROUND)
// GetDeviceState(0x14) -> lX / lY (raw mickeys since the last read), lZ (the wheel's sign
// is kept), rgbButtons[8] (PHYSICAL buttons; the poller swaps 0 / 1 when SM_SWAPBUTTON);
// the absolute position from GetCursorPos + ScreenToClient. Legacy path: the cursor
// position difference, GetAsyncKeyState(VK_L/R/MBUTTON), the wheel from WM_MOUSEWHEEL.
//
// SDL:
//  * x / y: SDL_GetRelativeMouseState, drained every poll (so motion while unfocused is
//    not delivered at the refocus, as DirectInput's buffer is not). Outside relative mode
//    SDL's motion is the cursor-position difference (pointer acceleration applied, none
//    once the cursor stops at a screen edge); DirectInput's mickeys are raw. Measured
//    side by side (the I3 commit): equal inside the window at a 1:1 pointer setting,
//    0.60-0.68 of DirectInput's once the cursor pins at the edge. So the middle-button
//    drag runs in SDL's relative mode (raw, see SetRotateDrag).
//  * z: the queued wheel events since the last pump (WheelSinceLastPump), sign only
//    downstream, as lZ.
//  * buttons: live and LOGICAL (SDL applies SM_SWAPBUTTON itself), so ButtonsSwapped()
//    answers false under SDL and the poller's swap, kept at its call site, is not applied
//    twice. Buttons 5..7 are always up (SDL has five).
//  * not foreground: DIERR_NOTACQUIRED, the record untouched: the poller's failure exit
//    (all mouse inputs zero), as DISCL_FOREGROUND gave.
// ---------------------------------------------------------------------------
int32_t ReadMouse(void* /*device*/, MouseState* out) {
    float dx = 0.0f;
    float dy = 0.0f;
    SDL_GetRelativeMouseState(&dx, &dy);
    const float wheel = WheelSinceLastPump();

    if (!GameWindowHasKeyboardFocus()) {
        SetRotateDrag(false);
        g_remainderX = 0.0f;
        g_remainderY = 0.0f;
        return kNotAcquired;
    }

#if BANISHED_TWEAK_OVERLAY
    if (Diag::TweakOverlay::IsOpen()) {   // the debug tweak overlay has the mouse: no motion, wheel or button
        SetRotateDrag(false);
        g_remainderX = 0.0f;
        g_remainderY = 0.0f;
        std::memset(out, 0, sizeof(*out));
        return kOk;
    }
#endif
    g_remainderX += dx;
    g_remainderY += dy;
    const float ix = std::trunc(g_remainderX);
    const float iy = std::trunc(g_remainderY);
    g_remainderX -= ix;
    g_remainderY -= iy;
    out->x = static_cast<int32_t>(ix);
    out->y = static_cast<int32_t>(iy);    // down is positive, as DirectInput's lY
    out->z = (wheel > 0.0f) ? 120 : (wheel < 0.0f ? -120 : 0);

    const SDL_MouseButtonFlags b = LiveButtons();
    // Plan §G3 option (b): raw motion while the middle button (camera rotate) is held,
    // from the next poll on (this poll's motion was already read above).
    SetRotateDrag((b & SDL_BUTTON_MMASK) != 0);
    out->buttons[0] = (b & SDL_BUTTON_LMASK)  ? kDiKeyDown : 0;
    out->buttons[1] = (b & SDL_BUTTON_RMASK)  ? kDiKeyDown : 0;
    out->buttons[2] = (b & SDL_BUTTON_MMASK)  ? kDiKeyDown : 0;
    out->buttons[3] = (b & SDL_BUTTON_X1MASK) ? kDiKeyDown : 0;
    out->buttons[4] = (b & SDL_BUTTON_X2MASK) ? kDiKeyDown : 0;
    out->buttons[5] = 0;
    out->buttons[6] = 0;
    out->buttons[7] = 0;
    return kOk;
}

int16_t AsyncMouseButtonState(int32_t vk) {
#if BANISHED_TWEAK_OVERLAY
    if (Diag::TweakOverlay::IsOpen()) return 0;   // the debug tweak overlay has the mouse
#endif
    const SDL_MouseButtonFlags b = LiveButtons();
    SDL_MouseButtonFlags mask = 0;
    switch (vk) {
        case kVkLButton: mask = SDL_BUTTON_LMASK; break;
        case kVkRButton: mask = SDL_BUTTON_RMASK; break;
        case kVkMButton: mask = SDL_BUTTON_MMASK; break;
        default:         break;
    }
    return (b & mask) ? INT16_MIN : 0;
}

// GetCursorPos: SDL_GetGlobalMouseState is GetCursorPos on Windows (desktop pixels; the
// process is DPI-unaware, src/app/main.cpp). On macOS it is desktop POINTS; the engine's
// screen coordinates are pixels of the window's display (point * density), so the cursor
// is scaled here, and ScreenToClient / ClientToScreen / GetWindowRect / ClipCursor use the
// same unit. A cursor in the last point of the client area is snapped to the last pixel
// (CursorPointToPixel) so edge scrolling reaches the right and bottom edges.
void GetCursorPos(Point* out) {
    float x = 0.0f;
    float y = 0.0f;
    SDL_GetGlobalMouseState(&x, &y);
    SDL_Window* w = Window::Sdl::GameWindow();
    const float d = Window::PixelDensity(w);
    if (d == 1.0f || w == nullptr) {
        out->x = static_cast<int32_t>(std::floor(x));
        out->y = static_cast<int32_t>(std::floor(y));
        return;
    }
    int wx = 0, wy = 0, ww = 0, wh = 0;
    SDL_GetWindowPosition(w, &wx, &wy);
    SDL_GetWindowSize(w, &ww, &wh);
    out->x = Window::PointsToPixels(static_cast<float>(wx), d) +
             Window::CursorPointToPixel(x - static_cast<float>(wx), ww, d);
    out->y = Window::PointsToPixels(static_cast<float>(wy), d) +
             Window::CursorPointToPixel(y - static_cast<float>(wy), wh, d);
}

// ScreenToClient: SDL's window position is the client area's screen origin (the inverse
// of display_sdl.cpp's ClientToScreen). Off-window points stay negative / beyond the size.
void ScreenToClient(void* /*window*/, Point* inOut) {
    SDL_Window* w = Window::Sdl::GameWindow();
    int x = 0;
    int y = 0;
    if (w != nullptr) SDL_GetWindowPosition(w, &x, &y);
    // Screen coordinates are in engine pixels (GetCursorPos); the window origin is in
    // points, so it is scaled by the density first (identity unless Retina).
    const float d = Window::PixelDensity(w);
    inOut->x -= Window::PointsToPixels(static_cast<float>(x), d);
    inOut->y -= Window::PointsToPixels(static_cast<float>(y), d);
}

bool ButtonsSwapped() {
    // SDL's buttons are already logical (see ReadMouse): no second swap.
    return false;
}

int16_t AsyncKeyState(int32_t vk) {
#if BANISHED_TWEAK_OVERLAY
    if (Diag::TweakOverlay::IsOpen()) return 0;   // the debug tweak overlay has the keyboard
#endif
    int count = 0;
    bool scratch[kKeyLayerCapacity];
    const bool* state = EffectiveKeyState(&count, scratch);
    for (const uint16_t s : kVirtualKeyToSdlScancode[static_cast<uint8_t>(vk)]) {
        if (s != 0 && s < count && state[s]) return INT16_MIN;   // bit 15: down now
    }
    return 0;
}

