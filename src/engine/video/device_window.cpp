// ============================================================================
// ?SizeWindow@Device@Video@@SAHPEAUHWND__@@I_K_J@Z   retail 0x1800f7d20, ord 4064
// ============================================================================
// The WM_SIZE (id 5) callback. It records the new CLIENT size into the Device's
// back-buffer dimensions and raises `settingsChanged` — it does NOT resize
// anything itself; the next frame's `ApplyChangedSettings` does that.
//
// TWO GUARDS, both retail's and both load-bearing:
//   * `Device+0x9D` non-zero suppresses the whole body (0x1800f7d2d). That flag
//     is what the renderer raises while it is itself resizing, so a WM_SIZE
//     generated BY the resize does not re-enter it.
//   * `Configuration+0x40` (fullscreen) non-zero suppresses it too
//     (0x1800f7d3d): in exclusive fullscreen the back buffer is the display
//     mode, not the window.
//
// It computes the size from `GetClientRect`'s right-minus-left rather than from
// the LPARAM the message carries. That is not equivalent — the LPARAM is the
// client size at the time the message was POSTED, and this runs when it is
// DISPATCHED. Reproduced; the parameters are ignored exactly as retail ignores
// them.
//
// Returns 1 unconditionally (0x1800f7d75), including on both suppressed paths.
// ============================================================================
int Video::Device::SizeWindow(void* hwnd, unsigned /*msg*/,
                              uint64_t /*wParam*/, int64_t /*lParam*/) {
    Device* dev = Device::_singleton;
    if (!dev) return 1;
    if (dev->adjustingDisplay != 0) return 1;

    Configuration* cfg = Configuration::_singleton;
    if (cfg && cfg->fullscreen != 0) return 1;

    Platform::Rect rc;
    Platform::Window::GetClientRect(hwnd, &rc);
    const int32_t w = rc.right  - rc.left;
    const int32_t h = rc.bottom - rc.top;

    if (dev->backBufferWidth != static_cast<int32_t>(w) ||
        dev->backBufferHeight != static_cast<int32_t>(h)) {
        dev->settingsChanged  = 1;
        dev->backBufferWidth  = static_cast<int32_t>(w);
        dev->backBufferHeight = static_cast<int32_t>(h);
    }
    return 1;
}

// ============================================================================
// ?MoveWindow@Device@Video@@SAHPEAUHWND__@@I_K_J@Z   retail 0x1800f7d90, ord 3235
// ============================================================================
// The WM_EXITSIZEMOVE (id 0x232) callback: persist the window's top-left into
// `Video::Configuration` so the next run reopens where the player left it.
//
// Same two suppression guards as SizeWindow, then a THIRD that is easy to
// misread: it calls `GetWindowPlacement` and bails when `showCmd` is
// **0x20000000** or **2**. `2` is `SW_SHOWMINIMIZED` — do not record the
// position of a minimised window. `0x20000000` is not a documented SW_ value at
// all; it is what `WPF_RESTORETOMAXIMIZED` (0x0002) would be if it had been
// read out of `flags` instead of `showCmd`, and it is reproduced as the literal
// retail compares rather than "corrected" to a plausible constant.
//
// The position comes from `ClientToScreen` on a zeroed POINT — i.e. the screen
// coordinate of the client origin, NOT the window origin, so it excludes the
// border and title bar. That asymmetry is retail's and matters because
// `Configuration::windowX/Y` are fed straight back into window creation.
//
// Returns 1 unconditionally.
// ============================================================================
int Video::Device::MoveWindow(void* hwnd, unsigned /*msg*/,
                              uint64_t /*wParam*/, int64_t /*lParam*/) {
    Device* dev = Device::_singleton;
    if (!dev) return 1;
    if (dev->adjustingDisplay != 0) return 1;

    Configuration* cfg = Configuration::_singleton;
    if (cfg && cfg->fullscreen != 0) return 1;

    // GetWindowPlacement on a zeroed WINDOWPLACEMENT, length 0x2c (0x1800f7dbb — the
    // literal, = sizeof); 0x1800f7dc9 reads the DWORD at +0x08 of it, which is
    // `showCmd`.
    const uint32_t showCmd = Platform::Window::GetShowCmd(hwnd);
    if (showCmd == Platform::Window::kStyleMinimize || showCmd == Platform::Window::kShowCmdMinimized) return 1;

    Platform::Point pt;
    pt.x = 0; pt.y = 0;
    Platform::Window::ClientToScreen(hwnd, &pt);

    if (cfg) {
        cfg->windowX = pt.x;
        // Retail RE-READS the configuration singleton between the two stores
        // (0x1800f7df5). Nothing can move it; preserved anyway, because
        // "nothing can move it" is a claim about code this lane does not own.
        Configuration* cfg2 = Configuration::_singleton;
        if (cfg2) cfg2->windowY = pt.y;
    }
    return 1;
}

// ============================================================================
// ?GetDefaultResolution@Device@Video@@QEBAHAEBUAdapter@12@@Z
//                                                   retail 0x1800f7540, ord 2559
// ============================================================================
// Ask Windows what the desktop is running and return the index of the adapter
// mode that matches it, or 0 when none does.
//
// The DEVMODEW offsets are confirmed against retail's literals rather than
// assumed: `dmSize` is written at frame+0x44 (0x1800f7571), `dmPelsWidth` read
// at frame+0xAC (0x1800f7589) and `dmPelsHeight` at frame+0xB0 (0x1800f7594),
// and the memset length is 0xDC. All four match the SDK's DEVMODEW exactly, so
// the real struct is used here instead of a byte blob.
//
// `EnumDisplaySettingsW(nullptr, ENUM_CURRENT_SETTINGS, &dm)` — the -1 at
// 0x1800f757e is ENUM_CURRENT_SETTINGS. **Its return value is not checked**, so
// a failure leaves the memset zeros and the search below matches a 0x0 mode if
// the adapter happens to list one, and otherwise returns 0. Retail's; left
// unchecked.
//
// The `if (index < 0) index = 0` at 0x1800f75d8 is unreachable — the loop only
// ever produces a non-negative index or falls into the same `EBX = 0` — and is
// kept because removing an unreachable branch is how a transcription starts
// drifting from the thing it transcribes.
//
// The stack DisplayMode temp and its `~Array` call (0x1800f75e2) are kept for
// the reason device_startup.cpp gives for the same pattern in
// ValidateConfiguration.
// ============================================================================
int Video::Device::GetDefaultResolution(const Adapter& adapter) const {
    // The DEVMODEW set-up, the call and the two reads are Platform::Window's now.
    int32_t w;
    int32_t h;
    Platform::Window::GetCurrentDisplaySize(&w, &h);

    // Adapter::modeData / modeCount (+0x08 / +0x10); DisplayMode is 0x18 bytes
    // with width at +0x00 and height at +0x04 (Device.h asserts all four).
    const DisplayMode* const modeData = adapter.modeData;
    const int32_t            modeCount = adapter.modeCount;

    int32_t index = 0;
    bool found = false;
    for (int32_t i = 0; i < modeCount; ++i) {
        const DisplayMode& m = modeData[i];
        if (m.width == w && m.height == h) { index = i; found = true; break; }
    }
    if (!found) index = 0;
    if (index < 0) index = 0;            // 0x1800f75d8 — unreachable, kept
    return index;
}
