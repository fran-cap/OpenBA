#!/usr/bin/env python3
"""tools/ice_texture_bake.py -- ext.winter_ice's ice surface textures (docs/extensions/handins/WINTERICE.md).

Reads the CC0 "Ice003" material from ambientCG (https://ambientcg.com/view?id=Ice003, the 1K-JPG set:
Ice003_1K-JPG_Color.jpg, _NormalGL.jpg, _Roughness.jpg, _Displacement.jpg; not checked in) and writes
src/ext/winter_ice/ice_texture_data.h: two SIZE x SIZE planes of straight RGBA8, row-major, top-down --

    kIceSurface  rgb = the colour (as the photograph's sRGB values: the game shades in gamma space),
                 a   = the roughness
    kIceDetail   r, g = the normal's x and y (OpenGL convention, 0.5 = flat), b = the displacement
                 (the fake inner layer's depth), a = 255

Only the top level is baked; the exe builds the mip chain at load (winter_ice_texture.cpp). The
resize is a Lanczos filter of the whole 1024 image, which keeps the material tileable.

    python tools/ice_texture_bake.py [SOURCE_DIR]      (needs Pillow; default ~/Downloads/Ice003_1K-JPG)
"""
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "ext", "winter_ice", "ice_texture_data.h")
SIZE = 256
PREFIX = "Ice003_1K-JPG_"


def load(src, name, mode):
    im = Image.open(os.path.join(src, PREFIX + name + ".jpg")).convert(mode)
    return im.resize((SIZE, SIZE), resample=Image.LANCZOS)


def emit(f, var, data):
    f.write("inline constexpr uint8_t %s[kIceTextureSize * kIceTextureSize * 4] = {\n" % var)
    per_line = 32
    for i in range(0, len(data), per_line):
        f.write(",".join(str(b) for b in data[i:i + per_line]))
        f.write(",\n")
    f.write("};\n\n")


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.expanduser("~"), "Downloads", "Ice003_1K-JPG")
    color = load(src, "Color", "RGB")
    rough = load(src, "Roughness", "L")
    normal = load(src, "NormalGL", "RGB")
    disp = load(src, "Displacement", "L")

    surface = bytearray()
    detail = bytearray()
    cp, rp, np_, dp = color.load(), rough.load(), normal.load(), disp.load()
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b = cp[x, y]
            surface += bytes((r, g, b, rp[x, y]))
            nx, ny, _ = np_[x, y]
            detail += bytes((nx, ny, dp[x, y], 255))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/ice_texture_bake.py -- do not edit; rerun the script.\n")
        f.write("// NOT RETAIL. ambientCG \"Ice003\" (CC0 1.0, https://ambientcg.com/view?id=Ice003), resized to\n")
        f.write("// %d x %d; THIRD_PARTY_NOTICES.md. docs/extensions/handins/WINTERICE.md.\n" % (SIZE, SIZE))
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write("namespace Ext {\nnamespace WinterIce {\n\n")
        f.write("inline constexpr int kIceTextureSize = %d;\n\n" % SIZE)
        emit(f, "kIceSurface", surface)
        emit(f, "kIceDetail", detail)
        f.write("}  // namespace WinterIce\n}  // namespace Ext\n")
    print("wrote %s (%d x %d, two planes)" % (OUT, SIZE, SIZE))


if __name__ == "__main__":
    main()
