#!/usr/bin/env python3
"""tools/leaf_textures_bake.py -- natural tree growth's falling-leaf detail textures (NATURAL_GROWTH.md section 7).

Reads the CC0 leaf photographs images/foliage_15.png, foliage_19.png and foliage_50.png (desaturated, with
alpha; not checked in: about 45 MB) and writes src/ext/better_trees/leaf_textures_data.h: each leaf cropped
to its alpha, fitted into a 64 x 64 cell (2-texel clear margin, aspect kept, the long axis along the
cell's diagonal so the leaf fills the card), as two 8-bit planes -- the luminance, stretched so the leaf's
mean is kTargetMean and its detail is kept, and the alpha. The atlas colours them at load
(leaf_fall.cpp PaintAtlas).

    python tools/leaf_textures_bake.py          (needs Pillow)
"""
import os
import sys

from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ["foliage_15.png", "foliage_19.png", "foliage_50.png"]
CELL = 64
MARGIN = 2
TARGET_MEAN = 0.80   # the leaf's mean luminance after the stretch (the atlas multiplies the colour by it)
OUT = os.path.join(ROOT, "src", "ext", "better_trees", "leaf_textures_data.h")


def bake(path):
    im = Image.open(path).convert("RGBA")
    im = im.crop(im.split()[3].getbbox())
    # the long axis along the diagonal: rotate by 45 degrees (expand), then crop to the alpha again
    im = im.rotate(45, resample=Image.BICUBIC, expand=True)
    im = im.crop(im.split()[3].getbbox())
    inner = CELL - 2 * MARGIN
    scale = inner / max(im.size)
    size = (max(1, round(im.size[0] * scale)), max(1, round(im.size[1] * scale)))
    # premultiplied resize: no dark fringe from the transparent texels' colour
    lum = ImageOps.grayscale(im)
    alpha = im.split()[3]
    pre = Image.composite(lum, Image.new("L", lum.size, 0), alpha)
    pre = pre.resize(size, Image.LANCZOS)
    alpha = alpha.resize(size, Image.LANCZOS)
    cell_l = Image.new("L", (CELL, CELL), 0)
    cell_a = Image.new("L", (CELL, CELL), 0)
    at = ((CELL - size[0]) // 2, (CELL - size[1]) // 2)
    cell_l.paste(pre, at)
    cell_a.paste(alpha, at)
    lp = cell_l.load()
    ap = cell_a.load()
    lum_vals = []
    out_l = [[0] * CELL for _ in range(CELL)]
    for y in range(CELL):
        for x in range(CELL):
            a = ap[x, y]
            if a > 0:
                lum_vals.append(lp[x, y] / a)
    mean = sum(lum_vals) / max(1, len(lum_vals))
    gain = TARGET_MEAN / max(mean, 1e-3)
    for y in range(CELL):
        for x in range(CELL):
            a = ap[x, y]
            # un-premultiply; the colour of a clear texel is the leaf's mean (no fringe under filtering)
            v = (lp[x, y] / a) if a > 0 else mean
            out_l[y][x] = max(0, min(255, round(v * gain * 255)))
    out_a = [[ap[x, y] for x in range(CELL)] for y in range(CELL)]
    return out_l, out_a


def emit(name, plane):
    rows = []
    for row in plane:
        rows.append("    " + ",".join(str(v) for v in row) + ",")
    return "constexpr uint8_t %s[kLeafCell * kLeafCell] = {\n%s\n};\n" % (name, "\n".join(rows))


def main():
    leaves = []
    for s in SOURCES:
        path = os.path.join(ROOT, "images", s)
        if not os.path.exists(path):
            sys.exit("missing %s" % path)
        leaves.append(bake(path))
    parts = [
        "// src/ext/better_trees/leaf_textures_data.h -- GENERATED by tools/leaf_textures_bake.py; do not edit.\n",
        "// NOT RETAIL (docs/extensions/NATURAL_GROWTH.md section 7): three leaf photographs (CC0; images/foliage_15,\n",
        "// _19 and _50.png, THIRD_PARTY_NOTICES.md), each a 64 x 64 luminance plane (the leaf's mean stretched to\n",
        "// %.2f) and an alpha plane, row-major, top-down. leaf_fall.cpp colours them into the atlas.\n" % TARGET_MEAN,
        "#pragma once\n\n#include <cstdint>\n\n",
        "namespace Ext {\nnamespace BetterTrees {\nnamespace LeafFall {\n\n",
        "constexpr int kLeafCell = %d;\nconstexpr int kLeafPhotos = %d;\n\n" % (CELL, len(leaves)),
    ]
    for i, (l, a) in enumerate(leaves):
        parts.append(emit("kLeafLum%d" % i, l))
        parts.append(emit("kLeafAlpha%d" % i, a))
    parts.append("constexpr const uint8_t* kLeafLum[kLeafPhotos] = {%s};\n" %
                 ", ".join("kLeafLum%d" % i for i in range(len(leaves))))
    parts.append("constexpr const uint8_t* kLeafAlpha[kLeafPhotos] = {%s};\n\n" %
                 ", ".join("kLeafAlpha%d" % i for i in range(len(leaves))))
    parts.append("}  // namespace LeafFall\n}  // namespace BetterTrees\n}  // namespace Ext\n")
    with open(OUT, "w", newline="\n") as f:
        f.write("".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
