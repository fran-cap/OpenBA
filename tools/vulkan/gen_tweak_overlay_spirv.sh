#!/usr/bin/env bash
# tools/vulkan/gen_tweak_overlay_spirv.sh -- regenerate src/render/vulkan/tweak_overlay/overlay_spirv.h from
# the two GLSL sources beside it (the debug tweak overlay's Vulkan renderer; OpenBA's own shaders, no game
# content). SPIR-V 1.0 (vulkan1.0), so the module needs no downgrade on the 1.1 path. Needs glslc: the
# Vulkan SDK's (VULKAN_SDK), the NDK's shader-tools, or one on PATH.
#   tools/vulkan/gen_tweak_overlay_spirv.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
DIR="$ROOT/src/render/vulkan/tweak_overlay"
OUT="$DIR/overlay_spirv.h"

GLSLC=""
for cand in "${VULKAN_SDK:-/nonexistent}/Bin/glslc" "${VULKAN_SDK:-/nonexistent}/bin/glslc" \
            "${ANDROID_HOME:-/nonexistent}"/ndk/*/shader-tools/*/glslc; do
    if [ -x "$cand" ] || [ -x "$cand.exe" ]; then
        GLSLC="$cand"
        break
    fi
done
GLSLC="${GLSLC:-glslc}"

emit() {
    local stage="$1" src="$2" name="$3"
    echo "// $(basename "$src"), glslc -O --target-env=vulkan1.0 -fshader-stage=$stage"
    echo "static const uint32_t $name[] = "
    "$GLSLC" -O --target-env=vulkan1.0 -fshader-stage="$stage" -mfmt=c -o - "$src" | tr -d '\r'
    echo ";"
}

{
    echo "// src/render/vulkan/tweak_overlay/overlay_spirv.h -- GENERATED by tools/vulkan/gen_tweak_overlay_spirv.sh"
    echo "// from overlay.vert and overlay.frag (OpenBA's own shaders, not game content). Do not edit by hand."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo
    emit vert "$DIR/overlay.vert" kOverlayVertSpirv
    echo
    emit frag "$DIR/overlay.frag" kOverlayFragSpirv
} > "$OUT"
echo "wrote $OUT ($("$GLSLC" --version | head -1))"
